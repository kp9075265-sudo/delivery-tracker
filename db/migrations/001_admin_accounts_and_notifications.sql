BEGIN;

CREATE TABLE app_users (
  user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('admin', 'customer')),
  customer_id integer UNIQUE REFERENCES customers(customer_id),
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT app_users_role_customer_check
    CHECK ((role = 'admin' AND customer_id IS NULL) OR (role = 'customer' AND customer_id IS NOT NULL))
);

ALTER TABLE orders
  ADD COLUMN address_id integer REFERENCES addresses(address_id);

ALTER TABLE notifications
  ADD COLUMN order_id integer REFERENCES orders(order_id),
  ADD COLUMN read_at timestamp with time zone,
  ADD COLUMN event_key text;

CREATE UNIQUE INDEX notifications_event_key_unique
  ON notifications(event_key)
  WHERE event_key IS NOT NULL;
CREATE INDEX notifications_customer_read_idx
  ON notifications(customer_id, read_at, sent_at DESC);
CREATE INDEX notifications_order_idx
  ON notifications(order_id);
CREATE INDEX orders_address_idx
  ON orders(address_id);

LOCK TABLE orders, order_items, payments, shipments, tracking_updates, notifications
  IN ACCESS EXCLUSIVE MODE;

DO $$
DECLARE
  item record;
  sequence_name text;
  highest_id bigint;
BEGIN
  FOR item IN
    SELECT * FROM (VALUES
      ('orders', 'order_id'),
      ('order_items', 'order_item_id'),
      ('payments', 'payment_id'),
      ('shipments', 'shipment_id'),
      ('tracking_updates', 'tracking_id'),
      ('notifications', 'notification_id')
    ) AS ids(table_name, column_name)
  LOOP
    sequence_name := item.table_name || '_' || item.column_name || '_seq';
    EXECUTE format('CREATE SEQUENCE public.%I AS integer', sequence_name);
    EXECUTE format(
      'SELECT COALESCE(MAX(%I), 0)::bigint FROM public.%I',
      item.column_name,
      item.table_name
    ) INTO highest_id;

    PERFORM setval(
      format('%I.%I', 'public', sequence_name)::regclass,
      GREATEST(highest_id, 1),
      highest_id > 0
    );
    EXECUTE format(
      'ALTER TABLE public.%I ALTER COLUMN %I SET DEFAULT nextval(%L::regclass)',
      item.table_name,
      item.column_name,
      format('%I.%I', 'public', sequence_name)
    );
    EXECUTE format(
      'ALTER SEQUENCE public.%I OWNED BY public.%I.%I',
      sequence_name,
      item.table_name,
      item.column_name
    );
  END LOOP;
END
$$;

COMMIT;
